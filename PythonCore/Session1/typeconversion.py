'''
Type Conversion:It is used to convert one type of data reference into another type. 
'''
#string into int
age="32"
print("Age is:",age)
print("Data Type is:",type(age))
print("========")

age=int(age)
print("Age is:",age)
print("Data Type is:",type(age))
print("========")

#string into float
salary="23456.34"
print("salary is:",salary)
print("Data Type is:",type(salary))
print("========")
salary=float(salary)
print("salary is:",salary)
print("Data Type is:",type(salary))
print("========")

salary=str(salary)
print("salary is:",salary)
print("Data Type is:",type(salary))
print("========")
