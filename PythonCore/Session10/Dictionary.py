'''
Dictionary:
It is a built in datatype in python which is used to store hetergenous data in the form of key value pair.
It is mutable.
Syntax:
dicname = {
    key_name:value,
    key_name1:value,
    ...
    key_namen:value
}
=====
key:
It is immutable.
It can be any datatype like int,float,string,list,dictionary.
value:
It is mutable.
=========
'''

