'''
Membership Operator:
in, not in
They are used to test if a value or variable is part of a sequence,such as a string,list,tuple or dictionary.They return a Boolean value(True or false) based on whether the specified element is found.
'''

name = "rahul"
ch = "ra"
r = ch in name 
print(r)
r = ch not in name
print(r)
